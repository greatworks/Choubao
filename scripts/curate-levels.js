'use strict';

var fs = require('fs');
var os = require('os');
var path = require('path');
var workerThreads = require('worker_threads');

var START_LEVEL = Math.max(2, Number(process.env.START_LEVEL) || 2);
var END_LEVEL = Math.min(1000, Number(process.env.END_LEVEL) || 1000);
var REQUESTED_LEVELS = process.env.LEVELS
  ? process.env.LEVELS.split(',').map(Number).filter(function (levelNumber) {
    return levelNumber >= 2 && levelNumber <= 1000;
  })
  : null;
var QUICK_RETRY = 5;
var MAX_RETRY = Math.max(20, Number(process.env.MAX_RETRY) || 120);

function recipeEntry(levelNumber, retry, strict, score, level, analysis) {
  return {
    level: levelNumber,
    retry: retry,
    strict: strict,
    score: score,
    flips: (level.orientationFlips || []).slice(),
    solution: level.solution.slice(),
    analysis: analysis
  };
}

function curateLevel(levelNumber) {
  var generator = require('../src/level-generator');
  var best = null;
  var closest = null;
  for (var retry = 0; retry <= MAX_RETRY; retry += 1) {
      var level = generator.buildExtractedMazeCandidate(levelNumber, retry, {
        skipOrientationOptimization: true
      });
      var report = generator.validateLevel(level);
      var analysis = generator.analyzePuzzle(level);
      var targets = generator.denseReleaseTargets(level);
      if (generator.meetsDenseQuality(report, analysis, level)) {
        return recipeEntry(levelNumber, retry, true, 0, level, analysis);
      }
      if (
        report.valid &&
        report.density >= targets.minDensity &&
        report.boardDensity >= targets.minBoardDensity &&
        report.arrows >= targets.minArrows &&
        report.arrows <= targets.maxArrows &&
        analysis.longArrows >= targets.longArrows &&
        analysis.longArrows <= targets.maxLongArrows &&
        analysis.windingArrows >= targets.windingArrows
      ) {
        generator.optimizeCandidateOrientations(level);
        report = generator.validateLevel(level);
        analysis = generator.analyzePuzzle(level);
      }
      if (generator.meetsDenseQuality(report, analysis, level)) {
        return recipeEntry(levelNumber, retry, true, 0, level, analysis);
      }
      if (generator.meetsDenseReleaseFloor(report, analysis, level)) {
        var score = generator.scoreExtractedMaze(level, report, analysis);
        if (!best || score > best.score) {
          best = recipeEntry(levelNumber, retry, false, score, level, analysis);
        }
      }
      if (report.valid) {
        var closestScore = generator.scoreExtractedMaze(level, report, analysis);
        if (!closest || closestScore > closest.score) {
          closest = {
            score: closestScore,
            retry: retry,
            report: report,
            analysis: analysis
          };
        }
      }
      if (retry === QUICK_RETRY && best) {
        return best;
      }
      if (retry > QUICK_RETRY && best) {
        return best;
      }
  }
  return { level: levelNumber, retry: -1, strict: false, closest: closest };
}

function writeRetryModule(entries) {
  entries.sort(function (a, b) { return a.level - b.level; });
  var failures = entries.filter(function (entry) { return entry.retry < 0; });
  var existingPath = path.resolve(__dirname, '../src/level-retries.js');
  var values = require(existingPath).slice();
  while (values.length < 999) {
    values.push(0);
  }
  entries.forEach(function (entry) {
    if (entry.retry >= 0) {
      values[entry.level - 2] = {
        retry: entry.retry,
        flips: entry.flips,
        solution: entry.solution,
        analysis: entry.analysis
      };
    }
  });
  var rows = [];
  for (var index = 0; index < values.length; index += 1) {
    rows.push('  ' + JSON.stringify(values[index]));
  }
  var source = [
    "'use strict';",
    '',
    '// Generated by scripts/curate-levels.js. Index 0 corresponds to level 2.',
    'module.exports = [',
    rows.join(',\n'),
    '];',
    ''
  ].join('\n');
  fs.writeFileSync(existingPath, source, 'utf8');
  if (failures.length) {
    throw new Error('No qualifying retry for levels: ' + failures.map(function (entry) { return entry.level; }).join(', '));
  }
}

if (!workerThreads.isMainThread) {
  workerThreads.parentPort.on('message', function (levelNumber) {
    if (levelNumber === null) {
      workerThreads.parentPort.close();
      return;
    }
    workerThreads.parentPort.postMessage(curateLevel(levelNumber));
  });
} else {
  var workerCount = Math.max(1, Math.min(8, os.cpus().length - 1));
  var startedAt = Date.now();
  var levelsToCurate = REQUESTED_LEVELS || Array.from(
    { length: END_LEVEL - START_LEVEL + 1 },
    function (_, index) { return START_LEVEL + index; }
  );
  var totalLevels = levelsToCurate.length;
  var nextLevelIndex = 0;
  var entries = [];
  var finished = false;
  var workers = [];
  new Promise(function (resolve, reject) {
    function assign(worker) {
      if (nextLevelIndex < totalLevels) {
        worker.postMessage(levelsToCurate[nextLevelIndex]);
        nextLevelIndex += 1;
      } else {
        worker.postMessage(null);
      }
    }
    for (var workerIndex = 0; workerIndex < workerCount; workerIndex += 1) {
      var worker = new workerThreads.Worker(__filename);
      workers.push(worker);
      worker.on('message', function (entry) {
        entries.push(entry);
        if (entry.retry < 0) {
          console.log('No qualifying retry yet for level ' + entry.level + ': ' + JSON.stringify(entry.closest));
        }
        if (entries.length % 10 === 0 || entries.length === totalLevels) {
          var maxRetry = Math.max.apply(Math, entries.map(function (item) { return item.retry; }));
          console.log(
            'Curated ' + entries.length + '/' + totalLevels + ' levels in ' +
            Math.round((Date.now() - startedAt) / 1000) + 's; max retry ' + maxRetry
          );
        }
        if (entries.length === totalLevels) {
          finished = true;
          workers.forEach(function (activeWorker) {
            activeWorker.terminate();
          });
          resolve(entries);
          return;
        }
        assign(this);
      });
      worker.once('error', reject);
      worker.once('exit', function (code) {
        if (!finished && code !== 0) {
          reject(new Error('Curation worker exited with code ' + code));
        }
      });
      assign(worker);
    }
  }).then(function (entries) {
    writeRetryModule(entries);
    var retries = entries.map(function (entry) { return entry.retry; });
    var strictCount = entries.filter(function (entry) { return entry.strict; }).length;
    console.log(
      'Curated ' + entries.length + ' levels in ' + Math.round((Date.now() - startedAt) / 1000) +
      's; strict ' + strictCount + ', release-floor ' + (entries.length - strictCount) +
      ', max retry ' + Math.max.apply(Math, retries)
    );
  }).catch(function (error) {
    console.error(error && error.stack || error);
    process.exitCode = 1;
  });
}
